#!/usr/bin/env python3
"""zig/config-schema.json -> zig/src/core/settings_table.zig (the Zig table every reader indexes).

usage: gen_schema.py [--check]     (run from the engine's root; --check fails when the table is out of date)
Ids are append-only: a row may change, never vanish or change its id; the check below refuses either.
"""
import json
import subprocess
import sys

SCHEMA = "zig/config-schema.json"
OUT = "zig/src/core/settings_table.zig"


def z(s):
    out = ['"']
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


KIND_Z = {"enum": "choice"}
CHECK_Z = {"test": "tested", "none": "unchecked"}


def num(v):
    if v is None:
        return "null"
    return repr(float(v)) if not float(v).is_integer() else "%d.0" % int(v)


def lst(items):
    """A Zig list literal as zig fmt writes it: &.{} empty, &.{a} for one item, &.{ a, b } for more."""
    items = list(items)
    return "&.{}" if not items else "&.{%s}" % items[0] if len(items) == 1 else "&.{ %s }" % ", ".join(items)


def row_extras(r):
    """The optional per-row fields, as the Zig struct's tail."""
    ag = r.get("agent")
    agent = "null" if ag is None else ".{ .min = %s, .max = %s, .max_ttl_s = %d }" % (num(ag["min"]), num(ag["max"]), ag["max_ttl_s"])
    cost = [".{ .what = %s, .value = %s, .label = %s, .source = %s }" % (z(c["what"]), z(c["value"]), z(c["label"]), z(c["source"])) for c in r.get("cost", [])]
    requires = [z(x) for x in r.get("requires", [])]
    return ".env_override = %s, .out_changes = %s, .now_ok = %s, .agent = %s, .requires = %s, .cost = %s" % (
        "true" if r.get("env_override") else "false", "true" if r.get("out_changes") else "false", "false" if r.get("now_ok") is False else "true", agent, lst(requires), lst(cost))


def check_rows(rows, tabs):
    """Build checks: a row an agent may set is bounded (an API that validates a row with no bounds accepts anything), a cost
    says whether it was measured or estimated, and every row sits on a tab the schema lists."""
    names = {t["name"] for t in tabs}
    by_name = {r["name"] for r in rows}
    ids = [r["id"] for r in rows]
    assert all(a < b for a, b in zip(ids, ids[1:])), "rows must be in rising id order (settings.byId is a binary search over the table): %s" % next("%d before %d" % (a, b) for a, b in zip(ids, ids[1:]) if a >= b)
    for r in rows:
        assert r["tab"] in names, "%s: tab %r is not in tabs" % (r["name"], r["tab"])
        if "agent" in r["who"]:
            ag = r.get("agent")
            assert ag and r["min"] is not None and r["max"] is not None, "%s: who has agent, so min, max and agent{min,max,max_ttl_s} are required" % r["name"]
            assert ag["min"] <= ag["max"] and ag["max_ttl_s"] > 0, "%s: agent bounds" % r["name"]
        elif r.get("agent"):
            raise AssertionError("%s: agent bounds without who agent" % r["name"])
        for c in r.get("cost", []):
            assert c["label"] in ("measured", "estimated"), "%s: a cost is measured or estimated" % r["name"]
        lab = r.get("label", "")
        assert lab and len(lab) <= 40 and "_" not in lab and lab[0].isupper(), "%s: label is required, at most 40 characters, sentence case, no underscores" % r["name"]
        assert r["doc"].strip() and ("_" not in r["name"] or r["name"] not in r["doc"]) and r["env"] not in r["doc"], "%s: doc is required and never names the row or its environment variable" % r["name"]
        assert r["default"] != "" or r.get("default_text"), "%s: an empty default needs a default_text saying what the engine uses" % r["name"]
        for q in r.get("requires", []):
            assert q.split("=")[0] in by_name, "%s: requires names no row: %s" % (r["name"], q)


def render(d):
    rows = d["options"]
    tabs = d["tabs"]
    check_rows(rows, tabs)
    ids = [r["id"] for r in rows]
    envs = [r["env"] for r in rows]
    assert len(set(ids)) == len(ids), "duplicate option id"
    assert len(set(envs)) == len(envs), "duplicate env name"
    assert all(0 < i < 65536 for i in ids), "option ids are u16 and above 0"
    out = []
    out.append("//! GENERATED by tools/schema/gen_schema.py from zig/config-schema.json: do not edit by hand.\n")
    out.append("//! Every setting the engine reads: stable id, names, type, range, default, apply class, who may set it, doc.\n\n")
    out.append("const settings = @import(\"settings.zig\");\n\n")
    out.append("pub const schema_version: u32 = %d;\n\n" % d["schema_version"])
    out.append("pub const options = [_]settings.Option{\n")
    for r in rows:
        who = [".%s" % w for w in r["who"]]
        values = [z(v) for v in r["values"]]
        out.append(
            "    .{ .id = %d, .name = %s, .env = %s, .group = %s, .tab = %s, .kind = .%s, .unit = %s, .min = %s, .max = %s, .default = %s, .default_text = %s, .check = .%s, .apply = .%s, .secret = %s, .hidden = %s, .who = %s, .label = %s, .doc = %s, .values = %s, %s },\n"
            % (r["id"], z(r["name"]), z(r["env"]), z(r["group"]), z(r["tab"]), KIND_Z.get(r["kind"], r["kind"]), z(r["unit"]), num(r["min"]), num(r["max"]), z(r["default"]), z(r.get("default_text", "")), CHECK_Z[r["default_check"]], r["apply"], "true" if r.get("secret") else "false", "true" if r.get("hidden") else "false", lst(who), z(r["label"]), z(r["doc"]), lst(values), row_extras(r))
        )
    out.append("};\n\n")
    out.append("/// The tabs, in the order the page shows them.\n")
    out.append("pub const tabs = [_]settings.Tab{\n")
    for t in tabs:
        out.append("    .{ .name = %s, .title = %s, .about = %s },\n" % (z(t["name"]), z(t["title"]), z(t["about"])))
    out.append("};\n\n")
    out.append("/// Names that no longer exist: a start with one set (the environment or engine.cfg) is refused by name.\n")
    out.append("pub const retired = [_]settings.Retired{\n")
    for r in d.get("retired", []):
        out.append("    .{ .env = %s, .when = .%s, .why = %s },\n" % (z(r["env"]), r["when"], z(r["why"])))
    out.append("};\n")
    return "".join(out)


def main():
    d = json.load(open(SCHEMA))
    text = render(d)
    if "--check" in sys.argv:
        if open(OUT).read() != text:
            print("%s is out of date: run tools/schema/gen_schema.py" % OUT)
            sys.exit(1)
        print("settings_table.zig matches the schema (%d rows)" % len(d["options"]))
        return
    open(OUT, "w").write(text)
    print("wrote %s (%d rows)" % (OUT, len(d["options"])))


if __name__ == "__main__":
    main()
